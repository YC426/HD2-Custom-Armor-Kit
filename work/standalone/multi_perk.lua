                                    -- modifier rows are 16 BYTES each (32 hex
                                    -- chars), same as the merge write path
                                    local rb=rd(mptr,mcnt*16)
                                    if rb and #rb==mcnt*16 then
                                        for k=1,mcnt do m[k]=tohex(rb:sub((k-1)*16+1,k*16)) end
                                    else
                                        m=nil
                                    end
                                end
                                if m then
                                    local stats={}
                                    local scnt,sptr=u64(head,40),u64(head,32)
                                    if scnt and scnt>0 and scnt<=64 and sptr and sptr>65536 then
                                        local rb=rd(sptr,scnt*12)
                                        if rb and #rb==scnt*12 then
                                            for j=1,scnt do stats[j]=tohex(rb:sub((j-1)*12+1,j*12)) end
                                        end
                                    end
                                    RT[enum]={n=u32(head,4),m=m,s=stats}
                                    S.rows_rev=(S.rows_rev or 0)+1
                                    if not PERKS[enum] then
                                        log(string.format('new passive enum=%d captured (%d rows) - added to the picker',enum,mcnt))
                                    end
                                end
                            end
                        end
                    end
                    elseif typ==TYPE_ARMOR then
                        local head=rd(body,32)
                        if head then
                            local item=u32(head,0)
                            -- register EVERY catalog kit the sweep touches, not
                            -- just the wanted ones: a card can target any owned
                            -- armor, and records for rarely-viewed armors only
                            -- exist once the armory materializes them
                            if PIECES[item] and not S.kits[item] then
                                S.kits[item]={body=body,head=head}
                                S.kits_n=(S.kits_n or 0)+1
                                if conf_data.want_items[item] then
                                    log(string.format('kit record found: %x at 0x%x',item,body))
                                end
                            end
                        end
                    end
                    from=i+4
                end
                S.off=S.off+math.max(1,#buf-32)
                if S.off>=r.size then S.cur=nil end
            end
        end
        if S.carrier and scan_targets_ready(conf_data) then
            S.initial_scan_done=true
            M.scan_requested=nil
            log(string.format('auto-init: targets ready; read=%dMB elapsed=%.3fs',
                math.floor(S.scanned/1048576),os.clock()-(M.scan_started or os.clock())))
            break
        end
    end
    if S.scanned>=S.limit then S.scanning=false;log('scan limit reached') end
end

-- steady-state check: is the merge we last wrote still in place? One small
-- read, called every couple of seconds - this is the entire idle cost.
local function steady(c)
    if not c then return false end
    local head=rd(c.body,56)
    if not head then return false end
    if u32(head,0)~=c.enum then return false end
    if u32(head,4)~=(c.name_now or PERKS[c.enum].n) then return false end
    if u64(head,16)~=(c.buf_at or c.body+56) then return false end
    return true
end

local function drop_carrier(why)
    S.carrier=nil
    if S.last_region then
        S.region_until=S.last_region.base+S.last_region.size
        S.scanned,S.cursor,S.cur=0,S.last_region.base,nil
        log(why..' - region-first rescan (last allocation)')
    else
        S.scanned,S.cursor,S.cur=0,4294967296,nil
        log(why..' - full rescan')
    end
end

local function kits_ready(conf_data)
    for id_ in pairs(conf_data.want_items) do
        if not S.kits[id_] then return false end
    end
    return true
end

