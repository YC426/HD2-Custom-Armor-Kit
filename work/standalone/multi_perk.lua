    -- ASCII cell sized to match the 16px hanzi height so mixed text reads evenly
    local acell=math.max(2,math.floor((16*zcell)/5+0.5))
    local W8={8,4,2,1}
    local function zhdraw(x,y,key,c)
        local bm
        if type(key)=='table' then bm=key.r and key or nil else bm=ZH[key] end
        if not bm then return x end
        -- bottom-left origin: bitmap row 1 is the glyph TOP, so it must land
        -- at the HIGHEST y - rows were inverted here before (mirrored text)
        for r=1,#bm.r do
            local row=bm.r[r]
            for n=1,#row do
                local v=tonumber(row:sub(n,n),16) or 0
                for b=1,4 do
                    if math.floor(v/W8[b])%2==1 then
                        rect(x+((n-1)*4+b-1)*zcell,y+(bm.h-r)*zcell,zcell,zcell,c)
