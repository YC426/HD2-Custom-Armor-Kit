local function u32(s,o)
    if not s or #s<o+4 then return nil end
    local a,b,c,d=s:byte(o+1,o+4);return a+256*b+65536*c+16777216*d
end
local function u64(s,o)
    local lo,hi=u32(s,o),u32(s,o+4);if not lo or not hi then return nil end
    return lo+hi*4294967296
end
local function p32(v)
    v=math.floor(v)%4294967296
    local a=v%256;v=(v-a)/256;local b=v%256;v=(v-b)/256
    local c=v%256;v=(v-c)/256;return string.char(a,b,c,v%256)
end
local function p64(v) local lo=math.floor(v)%4294967296;return p32(lo)..p32((v-lo)/4294967296) end
local function unhex(s) return (s:gsub('%x%x',function(x) return string.char(tonumber(x,16)) end)) end
local rbuf=ffi.new('uint8_t[?]',262144)
local function rd(at,n)
    if type(at)~='number' or n<1 or n>262144 or at<65536 or at+n>=140737488355328 then return nil end
    local got=ffi.new('size_t[1]')
    if k.ReadProcessMemory(proc,ffi.cast('const void*',at),rbuf,n,got)==0 then return nil end
    if tonumber(got[0])~=n then return nil end
    return ffi.string(rbuf,n)
end
local function wr(at,bytes)
    local n=#bytes
    if type(at)~='number' or n<1 or n>4096 or at<65536 or at+n>=140737488355328 then return false,'range' end
    local mbi=ffi.new('uint8_t[48]')
    local changed,restore_prot=false,0
    if k.VirtualQuery(ffi.cast('const void*',at),mbi,48)==48 then
        local raw=ffi.string(mbi,48)
        restore_prot=u32(raw,36) or 0
        -- reject guard/noaccess/checkout pages outright (AD49's guarded()
        -- discipline): fighting them corrupts live engine state
        if restore_prot>=0x100 or restore_prot==0 then return false,'guarded' end
        local prot=restore_prot%256
        if prot~=4 and prot~=8 then
            local old=ffi.new('uint32_t[1]')
            if k.VirtualProtect(ffi.cast('void*',at),n,4,old)==0 then return false,'protect' end
            changed=true
        end
    end
    local got=ffi.new('size_t[1]')
    local okw=k.WriteProcessMemory(proc,ffi.cast('void*',at),ffi.cast('const void*',bytes),n,got)
    if changed and restore_prot~=0 then
        local old=ffi.new('uint32_t[1]')
        k.VirtualProtect(ffi.cast('void*',at),n,restore_prot,old)
    end
    if okw==0 or tonumber(got[0])~=n then return false,'write' end
    return rd(at,n)==bytes
end

