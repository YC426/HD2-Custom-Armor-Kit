    if not TEST_ENABLED or frames%30~=0 then return end
    local f=io.open(HOME..'MultiPerk/development.command','r')
    if not f then return end
    local line=f:read('*l');f:close()
    if not line or line==M.test_last_command then return end
    local serial,verb,arg=line:match('^(%d+)%s+(%S+)%s*(.-)%s*$')
    if not serial then return end
    M.test_last_command=line
    local ok,why
    if verb=='status' then
        ok=true
        local fg=u.GetForegroundWindow()
        u.GetWindowThreadProcessId(fg,ffi.cast('void *',ui_pid))
        u.GetCursorPos(ffi.cast('void *',ui_point))
        why=string.format('data_ready=%s scan_done=%s kits=%d frames=%d foreground_pid=%d game_pid=%d cursor=%d,%d',
            tostring(data_ship_ready()),tostring(S.initial_scan_done),S.kits_n or 0,frames,
            tonumber(ui_pid[0]),tonumber(k.GetCurrentProcessId()),tonumber(ui_point[0]),tonumber(ui_point[1]))
    elseif verb=='script' then
        local file=io.open(HOME..'MultiPerk/development.lua','r')
        if file then
            local body=file:read('*a');file:close()
            local load=loadstring or load
            local run,err=load(body,'own unattended game test')
            if run then
                ok,why=pcall(run,{M=M,S=S,bridge=VISBRIDGE,rd=rd,u32=u32,u64=u64,
                    ffi=ffi,log=log,conf=conf_data,apply=apply_card,restore=restore_all})
            else why=err end
        else why='local development script absent' end
    elseif verb=='tooltip' then
        M.test_tooltip_rows=tonumber(arg);ok=true;why=tostring(M.test_tooltip_rows)
    elseif verb=='apply' and data_ship_ready() then
        local card=card_by_label(conf_data,arg)
        if card then ok,why=apply_card(card,conf_data) else why='unknown card' end
    elseif verb=='restore' and data_ship_ready() then
        ok=restore_all();why=ok and 'restored' or 'restore pending'
    elseif verb=='presenter' and data_ship_ready() then
        local id=tonumber(arg)
        local owner=u64(rd(VISBRIDGE.base+0x347ce28,8) or '',0)
        local state=owner and rd(owner+17032+12,32)
        if (id==1 or id==5 or id==15) and state and u32(state,0)==0 and u32(state,28)==0 then
            local enter=ffi.cast('void (__fastcall *)(void *, int, void *)',VISBRIDGE.base+0x14c0350)
            enter(ffi.cast('void *',owner+17032),id,nil)
