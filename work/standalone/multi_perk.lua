    -- zhdraw; strings render CJK runs through the ZH phrase table and ASCII
    -- runs through the pixel font. Mixed strings (L('[ 打开 ]'), '已选 3')
    -- previously lost their CJK half to the ASCII fallback.
    local function asciirun(x,y,s,c,cell)
        local cx=x
        for i=1,#s do
            local g=GLYPHS[s:sub(i,i)]
            if g then
                for r=1,5 do
                    local row=g[r]
                    for col=1,4 do
                        if row:sub(col,col)=='1' then
                            rect(cx+(col-1)*cell,y+(5-r)*cell,cell,cell,c or white)
                        end
                    end
                end
            end
            cx=cx+5*cell
        end
        return cx
