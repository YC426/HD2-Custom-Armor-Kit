local function module_sha256(module)
    local path=ffi.new('uint16_t[32768]')
    local length=k.GetModuleFileNameW(module,path,32768)
    assert(length>0 and length<32768,'module path unavailable')
    local file=k.CreateFileW(path,0x80000000,7,nil,3,0x08000000,nil)
    assert(file~=nil and file~=ffi.cast('void*',-1),'module file unavailable')
    local bcrypt=ffi.load('bcrypt')
    local algorithm,hash=ffi.new('void*[1]'),ffi.new('void*[1]')
    local ok,result=pcall(function()
        local name=ffi.new('uint16_t[7]',{83,72,65,50,53,54,0})
        assert(bcrypt.BCryptOpenAlgorithmProvider(algorithm,name,nil,0)==0,'SHA256 provider')
        assert(bcrypt.BCryptCreateHash(algorithm[0],hash,nil,0,nil,0,0)==0,'SHA256 hash')
        local buffer,received=ffi.new('uint8_t[1048576]'),ffi.new('uint32_t[1]')
        while true do
            assert(k.ReadFile(file,buffer,1048576,received,nil)~=0,'module read')
            if received[0]==0 then break end
            assert(bcrypt.BCryptHashData(hash[0],buffer,received[0],0)==0,'SHA256 update')
        end
        local digest,hex=ffi.new('uint8_t[32]'),{}
        assert(bcrypt.BCryptFinishHash(hash[0],digest,32,0)==0,'SHA256 finish')
        for i=0,31 do hex[#hex+1]=string.format('%02X',digest[i]) end
        return table.concat(hex)
    end)
    if hash[0]~=nil then bcrypt.BCryptDestroyHash(hash[0]) end
    if algorithm[0]~=nil then bcrypt.BCryptCloseAlgorithmProvider(algorithm[0],0) end
    k.CloseHandle(file)
    if not ok then error(result) end
    return result
end
local VISBRIDGE={read=rd}
VISBRIDGE.verify=function()
    if VISBRIDGE.checked then return VISBRIDGE.verified==true end
    VISBRIDGE.checked=true
    local ok,why=pcall(function()
        local game,exe=k.GetModuleHandleA('game.dll'),k.GetModuleHandleA(nil)
        assert(game~=nil and exe~=nil,'game modules unavailable')
        VISBRIDGE.game_sha256=module_sha256(game)
        VISBRIDGE.exe_sha256=module_sha256(exe)
        assert(VISBRIDGE.game_sha256==ShipVisibility.game_sha256
            and VISBRIDGE.exe_sha256==ShipVisibility.exe_sha256,'unsupported game build')
        VISBRIDGE.base=tonumber(ffi.cast('uintptr_t',game))
        assert(rd(VISBRIDGE.base+0x14c0350,16)==unhex('48895c24084889742410574883ec208b'),'native presenter changed')
    end)
    VISBRIDGE.verified=ok
    log(ok and 'ui: native ship visibility build verified' or 'ui: visibility unavailable - '..tostring(why))
    return ok
end
-- Read the selected Text Language, not strings from an arbitrary loaded pack.
-- These offsets are used only after the existing exact-build verification.
local function read_game_language()
    if not VISBRIDGE.verify() then return nil end
    local base=VISBRIDGE.base
    local function pointer(at)
        local bytes=rd(at,8)
        local p=bytes and u64(bytes,0)
        if p and p>=65536 and p<140737488355328 then return p end
    end
    local settings=pointer(base+0x3326340)
    local bytes=settings and rd(settings+705712,4)
    local index=bytes and u32(bytes,0)
    if not index or index>=15 then return nil end
    local record=pointer(base+0x37c5650+index*8)
    local text=record and pointer(record+8)
    local value=text and (rd(text,16) or rd(text,8))
    if rd(settings+705712,4)~=bytes then return nil end
    local code=value and value:match('^(%a[%a%-]*)%z')
    if not code or #code>12 then return nil end
    local zh={cn=true,tw=true,zh=true,zhs=true,zht=true,['zh-CN']=true,['zh-TW']=true}
    return zh[code] and 'zh' or 'en',code
end
