local function region(at)
    local mbi=ffi.new('uint8_t[48]')
    if k.VirtualQuery(ffi.cast('const void*',at),mbi,48)~=48 then return nil end
    local s=ffi.string(mbi,48)
    return {base=u64(s,0),size=u64(s,24),state=u32(s,32),prot=u32(s,36),kind=u32(s,40)}
end
-- optional localization probe (probe=yes): sweeps readable memory for a
-- known Chinese perk name and dumps the bytes around each hit, so the game's
-- loc-table layout can be reverse-engineered from the log and perk names +
-- descriptions can later be read live instead of baked in at build time
local PROBE={done=false,cursor=4294967296,r=nil,off=0,hits=0}
local function probe_loc(deadline)
    local needle='肾上腺素除颤器'
    while os.clock()<deadline do
        if not PROBE.r then
            local r=region(PROBE.cursor)
            if not r or not r.size or r.size<1 then
                PROBE.done=true
                log('probe: pass complete, hits='..PROBE.hits)
                return
            end
            PROBE.cursor=r.base+r.size
            local prot=r.prot%256
            if r.state==0x1000 and prot~=0 and prot~=1 then
                PROBE.r,PROBE.off=r,0
            end
        end
        local r=PROBE.r
        if r then
            local n=math.min(4194304,r.size-PROBE.off)
            local base=r.base+PROBE.off
            local buf=n>0 and rd(base,n) or nil
            if buf then
                local from=1
                while true do
                    local s,e=buf:find(needle,from,true)
                    if not s then break end
                    PROBE.hits=PROBE.hits+1
                    if PROBE.hits<=8 then
                        -- the 32 bytes before the text often hold the loc id
                        local ctx=buf:sub(math.max(1,s-32),math.min(#buf,e+64))
                        local hex={}
                        for i=1,#ctx do hex[#hex+1]=string.format('%02x',ctx:byte(i)) end
                        log(string.format('probe hit %d at 0x%x ctx=%s',PROBE.hits,base+s-1,table.concat(hex,'')))
                    end
                    from=e+1
                end
            end
            -- plain advance (no overlap): a needle straddling a 4MB chunk
            -- edge is lost, but the loop always terminates
            PROBE.off=PROBE.off+n
            if PROBE.off>=r.size then PROBE.r=nil end
        end
    end
end

