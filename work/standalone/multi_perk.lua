    if M.lang=='en' and EN_ARMOR_NAMES then
        local s=EN_ARMOR_NAMES[string.format('%08x',id or 0)]
        if s then return s end
    end
    return ARMOR_NAMES[id] or string.format('%X',id or 0)
end

local function stats_rep(cls,owned)
    for _,id in ipairs(owned or {}) do
        if stats_class(id)==cls then return id end
    end
    return REP and REP[cls] or nil
end

-- the flat effect-row picker list: every UNIQUE modifier row across ALL
-- passives (live-captured rows win over the embedded catalog; the carrier's
-- own rows are excluded). Rows sharing an id are value variants of one
-- modifier type - the game only applies one, so the UI enforces exclusivity.
local function build_rows(carrier_enum)
    local list,seen={},{}
    local src={}
    for enum,rec in pairs(RT) do src[enum]=rec end
    for enum,p in pairs(PERKS) do
        if not src[enum] and p and p.m then src[enum]=p end
    end
    for enum,rec in pairs(src) do
        if enum~=carrier_enum then
            for _,h in ipairs(rec.m or {}) do
                if type(h)=='string' and #h==32
                    and h:sub(1,8)~='00000000' and h:sub(25,32)~='00000000'
                    and not seen[h] then
                    seen[h]=true
                    list[#list+1]=h
                end
            end
        end
    end
    local variants={}
    for _,h in ipairs(list) do
        local id=h:sub(1,8)
        variants[id]=(variants[id] or 0)+1
    end
    table.sort(list,function(a,b)
        local la=(ROWLABELS and ROWLABELS[a:sub(1,8)]) or a:sub(1,4)
        local lb=(ROWLABELS and ROWLABELS[b:sub(1,8)]) or b:sub(1,4)
        if la~=lb then return la<lb end
        return a<b
    end)
    return list,variants
end

local function selectable_perks(carrier_enum)
    local seen,keys={},{}
    for e in pairs(PERKS) do seen[e]=true end
    for e in pairs(RT) do seen[e]=true end
    for e in pairs(seen) do if e~=0 and e~=carrier_enum then keys[#keys+1]=e end end
    table.sort(keys)
    return keys
end

local function owned_list(conf_text)
    -- the config's comment header lists every owned armor: "# NAME = hexid"
    local t={}
    if conf_text then
        for id in conf_text:gmatch('#%s*[^%r\n]-%s*=%s*(%x%x%x%x%x%x%x%x)%s*[\r\n]') do
            t[#t+1]=tonumber(id,16)
        end
    end
    if #t==0 then
        for id in pairs(PIECES) do t[#t+1]=id end
        table.sort(t)
    end
    return t
end

local function cards_to_config(cards)
    local t={}
    for i,c in ipairs(cards) do
        local perks={}
        for _,p in ipairs(c.perks) do perks[#perks+1]=tostring(p) end
        t[#t+1]=string.format('card.%d=%s,%08x,%s,%s',i,c.label,c.look,
            c.stats and string.format('%08x',c.stats) or '',table.concat(perks,','))
    end
    return t
end

-- returns the new card list, or nil,reason
local function save_cards(newlist)
    local f=io.open(CFG,'r')
    if not f then return nil,'config unreadable' end
    local text=f:read('*a') f:close()
    local lines={}
    for line in text:gmatch('[^\r\n]+') do
        if not line:match('^%s*card%.') then lines[#lines+1]=line end
    end
    for _,cline in ipairs(cards_to_config(newlist)) do lines[#lines+1]=cline end
    local body=table.concat(lines,'\n')..'\n'
    local w=io.open(CFG,'w')
    if not w then return nil,'config unwritable' end
    w:write(body) w:close()
    M.conf_text=nil -- force the next frame to re-read the file
    return true
end

-- drawing only: the gui object and the bound material come from the ladder
-- Stable identity number per world object, so log lines can say whether two
-- worlds are the same one (tostring(world) is just "[World]" for every world).
local function world_serial(world)
    if world==nil then return 0 end
    local map=M.ui_worlds
    if not map then
        map=setmetatable({},{__mode='k'})
        M.ui_worlds=map
    end
    local n=map[world]
    if not n then
        M.ui_world_n=(M.ui_world_n or 0)+1
        n=M.ui_world_n
        map[world]=n
    end
    return n
end

