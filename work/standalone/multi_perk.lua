-- apply one custom card: merged perks -> carrier, stats weights and the
-- passive reference -> the look armor's own kit record (snapshotted first so
-- restore brings the vanilla armor back byte for byte)
local function apply_card(c,conf_data)
    if not conf_data.write then
        log('dry run: card '..c.label..' (write=no)')
        return nil,'effect writing disabled (write=no)'
    end
    local kit=S.kits[c.look]
    if not kit then
        -- a full sweep done and still no record: the game only materializes
        -- kit records for armors the armory has shown
        if S.pass_done then
            return nil,'armor record not in memory - view that armor in the armory once, then retry'
        end
        return nil,'armor record not found yet (scanning)'
    end
    local head=rd(kit.body,32)
    if not head or u32(head,0)~=c.look then
        S.kits[c.look]=nil
        return nil,'armor record moved - rescanning'
    end
    M.claims=M.claims or {}
    M.actives=M.actives or {}
    S.carriers=S.carriers or {}
    if S.carrier and S.carrier.enum~=0 and not S.carriers[S.carrier.enum] then
        S.carriers[S.carrier.enum]=S.carrier
    end
    local active=M.actives[c.look]
    local carr=active and active.enum and S.carriers[active.enum] or nil
    local sn=M.snaps and M.snaps[c.look]
    local native=u32(sn and sn.passive or head:sub(29,32),0) or 0
    -- Different native passives can retain separate effect buffers. Prefer
    -- the look's original record, then a genuinely unused fallback. A claimed
    -- native record must not be overwritten by another armor's card.
    if #c.perks>0 and not carr and native~=0 and not M.claims[native] then
        carr=S.carriers[native]
    end
    if #c.perks>0 and not carr then
        local excluded={[0]=true,[native]=true}
        for _,token in ipairs(c.perks) do
            local en=type(token)=='number' and token or tonumber(tostring(token):match('^(%d+)%.'))
            if en then excluded[en]=true end
        end
        local candidates={}
        for en,record in pairs(S.carriers) do
            if PERKS[en] and (not OWNED or (OWNED[en] or 0)==0)
                and not excluded[en] and not M.claims[en] and record.body then
                candidates[#candidates+1]=en
            end
        end
        table.sort(candidates,function(a,b)
            if a==conf_data.carrier then return true end
            if b==conf_data.carrier then return false end
            local ua,ub=OWNED and OWNED[a] or 0,OWNED and OWNED[b] or 0
            return ua==ub and a<b or ua<ub
        end)
        if candidates[1] then carr=S.carriers[candidates[1]] end
    end
    if #c.perks>0 and not carr then
        if native~=0 and PERKS[native] and not S.carriers[native] then M.scan_requested=true end
        for en in pairs(PERKS) do
            if en~=0 and (OWNED[en] or 0)==0 and not S.carriers[en] then M.scan_requested=true end
        end
        return nil,'no unused independent carrier available; existing cards and original armors were kept'
    end
    if not M.snaps then M.snaps={} end
    if not M.snaps[c.look] then
        local tp=PIECES[c.look]
        local area=tp and #tp>0 and rd(kit.body+0x98,0x60*#tp) or nil
        if tp and not area then return nil,'piece area unreadable' end
        M.snaps[c.look]={body=kit.body,passive=head:sub(29,32),area=area}
    end
    local carrier_before=carr and rd(carr.body,56)
    local merged_result
    local area_before=M.snaps[c.look].area and rd(kit.body+0x98,#M.snaps[c.look].area)
    local function rollback()
        wr(kit.body+28,head:sub(29,32))
        if area_before then wr(kit.body+0x98,area_before) end
        if carrier_before then
            wr(carr.body+4,carrier_before:sub(5,8))
            wr(carr.body+16,carrier_before:sub(17,32))
            wr(carr.body+32,carrier_before:sub(33,48))
        end
    end
    if #c.perks>0 then
        local merged,why=merge_carrier(carr,c.perks,conf_data.rows)
        if not merged then return nil,why end
        merged_result=merged
        local okp,whyp=wr(kit.body+28,p32(carr.enum))
        if not okp or rd(kit.body+28,4)~=p32(carr.enum) then
            rollback()
            return nil,'passive field write '..tostring(whyp)
        end
    end
    if c.stats and c.stats~=c.look then
        local tp,dp=PIECES[c.look],PIECES[c.stats]
        if not tp or not dp then
            log('card '..c.label..': piece table missing - stats skipped')
        else
            local base=kit.body+0x98
            local changed,bad=0,0
            for i=1,#tp do
                local body,slot,typ=tp[i][1],tp[i][2],tp[i][3]
                local want
                for j=1,#dp do
                    if dp[j][1]==body and dp[j][2]==slot and dp[j][3]==typ then want=dp[j][4] end
                end
                if want then
                    local at=base+(i-1)*0x60
                    local okw=wr(at,p32(want))
                    if okw and rd(at,4)==p32(want) then changed=changed+1 else bad=bad+1 end
                end
            end
            log(string.format('card %s: stats %x->%x pieces=%d changed=%d failed=%d',
                c.label,c.look,c.stats,#tp,changed,bad))
            if bad>0 then rollback() return nil,'weight writes did not stick ('..bad..')' end
        end
    end
    M.active_card=c
    if merged_result then carr.name_now,carr.buf_at=merged_result.name,merged_result.at end
    M.actives[c.look]={card=c,enum=carr and carr.enum or nil}
    if carr then M.claims[carr.enum]=c.look end
    save_active_labels()
    M.booted=true
    M.scan_requested=nil
    log(string.format('CARD APPLIED label=%s look=%x stats=%s perks=%d carrier=%d',
        c.label,c.look,c.stats and string.format('%x',c.stats) or '-',#c.perks,carr and carr.enum or 0))
    return true
end

local function restore_all()
    local pending=false
    for look,sn in pairs(M.snaps or {}) do
        local kit=S.kits[look]
        local ok=kit and kit.body==sn.body and wr(kit.body+28,sn.passive)
        if ok and sn.area and rd(kit.body+0x98,#sn.area)~=sn.area then ok=wr(kit.body+0x98,sn.area) end
        if ok then
            M.snaps[look]=nil
            local a=M.actives and M.actives[look]
            if a and a.enum and M.claims then M.claims[a.enum]=nil end
            if M.actives then M.actives[look]=nil end
        else pending=true end
    end
    for en,carr in pairs(S.carriers or {}) do
        local orig=M.orig and M.orig[en]
        if orig and carr.name_now and not (M.claims and M.claims[en]) then
            local ok=wr(carr.body+4,orig:sub(5,8))
            ok=wr(carr.body+16,orig:sub(17,32)) and ok
            ok=wr(carr.body+32,orig:sub(33,48)) and ok
            if ok then carr.name_now,carr.buf_at=nil,nil else pending=true end
        end
    end
    local c=S.carrier
    if c and not (M.claims and M.claims[c.enum]) then
        local orig=M.orig and M.orig[c.enum]
        if orig and c.name_now then
            local ok=wr(c.body+4,orig:sub(5,8))
            ok=wr(c.body+16,orig:sub(17,32)) and ok
            ok=wr(c.body+32,orig:sub(33,48)) and ok
            if not ok then pending=true else c.name_now,c.buf_at=nil,nil end
        end
    end
    if not pending then M.active_card=nil M.actives={} M.claims={} end
    save_active_labels()
    log(pending and 'restore pending - unreadable or guarded records kept for retry' or 'restored - all custom cards removed, vanilla armors back')
    return not pending
end

local function steady_all()
    for look,a in pairs(M.actives or {}) do
        if a.enum then
            local carr=S.carriers[a.enum]
            if not steady(carr) then return false end
            local kit=S.kits[look]
            if not kit or rd(kit.body+28,4)~=p32(a.enum) then return false end
        end
    end
    return true
end

local function is_card_active(c)
    local a=M.actives and M.actives[c.look]
    return a and a.card.label==c.label
end

