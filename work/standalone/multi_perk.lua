            -- mixed text: scale the pixel font to the Chinese glyph height
            local amix=math.max(1,math.floor((16*zcell)/5+0.5))
            local i,cx=1,x
            while i<=#s do
                local hi=s:byte(i)>=128
                local j=i
                while j<=#s and (s:byte(j)>=128)==hi do j=j+1 end
                local seg=s:sub(i,j-1)
                if hi then
                    local key=seg:match('^%s*(.-)%s*$')
                    if ZH[key] then
                        cx=zhdraw(cx,y,key,c or white)
                    else
                        -- per-character fallback through the generic hanzi
                        -- font, so runtime text read from game memory (new
                        -- perks after updates) still renders; unknown chars
                        -- advance one blank cell-width
                        local ci=1
                        while ci<=#seg do
                            local b=seg:byte(ci)
                            local ln=(b>=0xF0 and 4) or (b>=0xE0 and 3) or (b>=0xC0 and 2) or 1
                            local ch=seg:sub(ci,ci+ln-1)
                            if ZH[ch] then
                                cx=zhdraw(cx,y,ch,c or white)
                            else
                                cx=cx+16*zcell
                                if not M.zh_miss then M.zh_miss=true log('zh: a character is outside the packed font') end
                            end
                            ci=ci+ln
                        end
                    end
                else
                    cx=asciirun(cx,y,seg,c,amix)
                end
                i=j
            end
            return cx
        end
        return asciirun(x,y,s,c,acell_ or acell)
