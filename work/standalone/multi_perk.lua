local function visibility_diagnostics(frames,info)
    if M.visibility_probe_done then return end
    local sr=rawget(_G,'stingray')
    if type(sr)~='table' then return end
    local function member(group,name)
        local t=sr[group]
        return type(t)=='table' and t[name] or nil
    end
    local function call(fn,...)
        if type(fn)~='function' then return false,'API '..type(fn) end
        return pcall(fn,...)
    end
    local network_session=member('Network','game_session')
    local session_check=member('GameSession','in_session')
    local oks,session=call(network_session)
    local oki,in_session=false,'not_checked'
    -- pcall only catches Lua failures. A nil native session can access-violate.
    if oks and session~=nil and session~=false then oki,in_session=call(session_check,session) end
    if not M.visibility_api_logged then
        M.visibility_api_logged=true
        local types={}
        for _,spec in ipairs({{'Application','main_world'},{'Application','worlds'},
            {'World','units_by_resource'},{'Unit','alive'},{'IdString64','from_hex'},
            {'Network','game_session'},{'GameSession','in_session'}}) do
            types[#types+1]=spec[1]..'.'..spec[2]..'='..type(member(spec[1],spec[2]))
        end
        log('ui gate API: '..table.concat(types,' ')..' session_ok='..tostring(oks)
            ..' session_type='..type(session)..' in_session_ok='..tostring(oki)
            ..' in_session_type='..type(in_session)..' value='..tostring(in_session))
    end
    -- Inspect worlds once the gate has authorized a ship scene (either a real
    -- session or the confirmed marker fallback), so a title-screen sample does
    -- not use up the only bounded read-only scene survey before the ship loads.
    if not (M.ship_ok or (info and info.session)) then return end
    M.visibility_probe_done=true
    local ok,err=pcall(function()
        local okm,main=call(member('Application','main_world'))
        local okw,worlds=call(member('Application','worlds'))
        log('ui gate survey: main_ok='..tostring(okm)..' main='..tostring(main)
            ..' worlds_ok='..tostring(okw)..' worlds_type='..type(worlds)
            ..' worlds_count='..(type(worlds)=='table' and #worlds or 0))
        if okw and type(worlds)=='table' then
            local ids={}
            for i,hex in ipairs({'be0be6b1875a4a66','ce2566805c9e893a','3b9bcf29e38da0a6'}) do
                local good,id=call(member('IdString64','from_hex'),hex)
                ids[i]={ok=good and id~=nil and id~=false,id=id,hex=hex}
            end
            for i=1,math.min(16,#worlds) do
                local fields={}
                for _,id in ipairs(ids) do
                    local good,units=false,nil
                    if id.ok then good,units=call(member('World','units_by_resource'),worlds[i],id.id) end
                    local n=type(units)=='table' and #units or -1
                    local alive=0
                    if good and type(units)=='table' then
                        for j=1,math.min(4,#units) do
                            local oka,a=call(member('Unit','alive'),units[j])
                            if oka and a==true then alive=alive+1 end
                        end
                    end
                    fields[#fields+1]=id.hex..':ok='..tostring(good)..',n='..n..',alive_sample='..alive
                end
                log('ui gate world '..i..' main='..tostring(worlds[i]==main)
                    ..' id='..tostring(worlds[i])..' '..table.concat(fields,' '))
            end
        end
        -- Absolute native offsets are never inspected without a real build proof.
        if VISBRIDGE.verify() then
            local owner=u64(rd(VISBRIDGE.base+0x347ce28,8) or '',0)
            local native=owner and owner>=65536 and rd(owner+0x4294,0x90) or nil
            if native then
                log(string.format('ui gate native: current=%s pending=%s depth=%s secondary=%s secondary_pending=%s',
                    tostring(u32(native,0)),tostring(u32(native,4)),tostring(u32(native,0x1c)),
                    tostring(u32(native,0x84)),tostring(u32(native,0x8c))))
            else log('ui gate native: verified build, UI state unreadable') end
        else log('ui gate native: unavailable (build not verified)') end
    end)
    if not ok then log('ui gate survey error: '..tostring(err)) end
end

