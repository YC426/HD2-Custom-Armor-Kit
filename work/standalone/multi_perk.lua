-- staged bring-up: one logged engine milestone every 5s, each run once.
local LNAMES={'create gui','bind material','dance (off)','dance (off)','dance (off)','draw panel','text (off)','finalize'}
local function ladder_step(n,conf_data,rw,rh)
    local sr=rawget(_G,'stingray')
    for _,kk in ipairs({'World','Gui','IdString64','Vector2','Vector3','Color'}) do
        local t=type(sr and sr[kk])
        if t~='table' and t~='function' then
            return false,'stingray.'..kk..' unavailable ('..t..')'
        end
    end
    if type(sr.IdString64)~='table' or type(sr.IdString64.from_hex)~='function' then
        return false,'IdString64.from_hex unavailable'
    end
    local G=sr.Gui
    if n==1 then
        local okg,gui=pcall(sr.World.create_screen_gui,PANEL.world,'scale',1,1)
        if not okg or gui==nil then return false,'create: '..tostring(gui) end
        PANEL.gui=gui
        PANEL.draw_guis={{world=PANEL.world,gui=gui}}
        -- Never allocate in other worlds: that experiment caused a native
        -- crash. Armory authorization only keeps this owned ship GUI alive.
        return true
    end
    if not PANEL.gui then return false,'gui lost before step '..n end
    if n==2 then
        -- bind only proves the id resolves; the ink is intentionally unused
        local id=sr.IdString64.from_hex
        local material=id(string.format('%016x',M.ui_material or 0))
        local oki,ink=pcall(G.material,PANEL.gui,material)
        if not oki then return false,'G.material error: '..tostring(ink) end
        PANEL.ink=nil
        return true
    end
    if n==3 or n==4 or n==5 then
        -- DISABLED: the material parameter dance faults at native level on
        -- this setup even with a verified id64. Rects need no material.
        return true,'skipped (material dance disabled)'
    end
    if n==6 then
        panel_draw(conf_data,rw,rh)
        return true
    end
    if n==7 then
        return true,'skipped (text off; labels are pixel-rects)'
    end
    if n==8 then return true end -- step 6 already drew the retained primitives
    return false,'unknown step'
end

-- Read-only menu rendering diagnostic, bounded to one line per 120 frames.
-- While the gate keeps the panel up for a named native screen, record what the
-- panel machinery actually did: whether the ship world was still resolved,
-- whether a GUI existed, and how far the staged ladder got. One line per 120
-- frames and silent on every other scene, so normal play is unaffected.
local function ui_world_count()
    local sr=rawget(_G,'stingray')
    if type(sr)~='table' or type(sr.Application)~='table' then return 0 end
    local ok,list=pcall(sr.Application.worlds)
    if ok and type(list)=='table' then return #list end
    return 0
end
local function data_ship_ready()
    local info=M.gate_info
    if not VISBRIDGE.verify() or not info or info.in_session~=true then return false end
    -- Rendering diagnostics are sampled. Re-read the native presenter before
    -- every data operation so a newly opened menu cannot receive writes while
    -- the previous sampled screen still says idle.
    local slot=VISBRIDGE.base+0x347ce28
    local owner_bytes=rd(slot,8)
    local owner=owner_bytes and u64(owner_bytes,0)
    if not owner or owner<65536 then return false end
    local state=rd(owner+0x4294,0x90)
    if not state or #state~=0x90 then return false end
    local current,pending,depth=u32(state,0),u32(state,4),u32(state,0x1c)
    if pending~=0 or u32(state,0x84)~=0 or u32(state,0x8c)~=0 then return false end
    if not ((current==0 and depth==0)
        or (current==1 and depth==1 and u32(state,8)==1)) then return false end
    if ui_world_count()<8 then return false end
    return rd(slot,8)==owner_bytes and rd(owner+0x4294,0x90)==state
end
