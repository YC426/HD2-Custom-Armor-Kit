local function scan_targets_ready(conf_data)
    local needed,available=0,0
    local native={}
    for look in pairs(conf_data.want_items) do
        local kit=S.kits[look]
        if not kit then return false end
        local head=rd(kit.body,32)
        if not head or u32(head,0)~=look then S.kits[look]=nil;return false end
        local en=u32(head,28)
        if en and en~=0 then native[en]=true end
        needed=needed+1
    end
    for en in pairs(S.carriers) do
        if en~=0 and (native[en] or (OWNED[en] or 0)==0) then available=available+1 end
    end
    return needed==0 or available>=needed
end
