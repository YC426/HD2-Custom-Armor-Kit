local function compose(list,budget)
    budget=math.min(11,budget or 11)
    local mods,stats,seen,name=nil,nil,{},nil
    for _,it in ipairs(list) do
        local enum,ri
        if type(it)=='string' and #it==32 and not it:find('.',1,true) then
            -- full row-hex token (from the flat picker): merge it directly
            local id,loc=it:sub(1,8),it:sub(25,32)
            if id~='00000000' and not seen['m'..id] then
                seen['m'..id]=true;mods=(mods or '')..it
            end
        elseif type(it)=='string' then
            -- legacy row token 'enum.ri': exactly one modifier row
            local en,r=it:match('^(%d+)%.(%d+)$')
            if not en then return nil,'bad row token '..tostring(it) end
            enum,ri=tonumber(en),tonumber(r)
            local vanilla,runtime=PERKS[enum],RT[enum]
            local p=runtime and {n=runtime.n or (vanilla and vanilla.n),m=runtime.m,
                s=runtime.s or (vanilla and vanilla.s)} or vanilla
            if not p then return nil,'perk '..enum..' unknown' end
            name=name or p.n
            local h=p.m and p.m[ri]
            if not h then return nil,'perk '..enum..' has no row '..ri end
            local id,loc=h:sub(1,8),h:sub(25,32)
            if id~='00000000' and not seen['m'..id] then
                seen['m'..id]=true;mods=(mods or '')..h
            end
        else
            enum=it
            local vanilla,runtime=PERKS[enum],RT[enum]
            local p=runtime and {n=runtime.n or (vanilla and vanilla.n),m=runtime.m,
                s=runtime.s or (vanilla and vanilla.s)} or vanilla
            if not p then return nil,'perk '..tostring(enum)..' unknown' end
            name=name or p.n
            for _,h in ipairs(p.m or {}) do
                local id,loc=h:sub(1,8),h:sub(25,32)
                if id~='00000000' and not seen['m'..id] then
                    seen['m'..id]=true;mods=(mods or '')..h
                end
            end
            do -- keep native stat modifiers; these implement dynamic effects
                for _,h in ipairs(p.s or {}) do
                    local id=h:sub(1,8)
                    if not seen['s'..id] then seen['s'..id]=true;stats=(stats or '')..h end
                end
            end
        end
    end
    if not mods then return nil,'no effect rows' end
    local nmod,nstat=math.floor(#mods/32),stats and math.floor(#stats/24) or 0
    -- NEVER byte-cut an oversize merge: a truncated record reads back fine
    -- from memory but fastfails the game (game.dll 0xC0000409, observed twice
    -- from the armory) the moment the UI walks it. Refuse instead. The row
    -- stable release caps the deduplicated effect rows at eleven, including
    -- legacy configs requesting a larger budget.
    if nmod+nstat>budget then
        return nil,string.format('too many perk effect rows (%d, budget %d) - deselect some perks',nmod+nstat,budget),{nmod=nmod,nstat=nstat}
    end
    -- row ids ride along so merge can log them (merge has no access to
    -- this scope - logging pairs(seen) there crashed every apply)
    local ids={}
    for k in pairs(seen) do
        if k:sub(1,1)=='m' then ids[#ids+1]=k:sub(2) end
    end
    table.sort(ids)
    return {mods=unhex(mods),stats=stats and unhex(stats) or '',nmod=nmod,nstat=nstat,name=name,rows=ids}
end

