-- One card row action, shared by the mouse path (a click on the row) and the
-- keyboard path (the row's number key), so the dock stays usable even when the
-- scene refuses to show a pointer at all.
local function card_action(conf_data,index)
    local c=conf_data.cards[index]
    if not c then return end
    if is_card_active(c) then
        log('ui: card '..c.label..' is already active')
        return
    end
    local ok,why=apply_card(c,conf_data)
    if ok then
        M.notice=nil
        log('ui: card '..c.label..' applied')
    else
        if tostring(why):find('write=no',1,true) then
            M.notice=M.lang=='en' and 'Effect writing is disabled' or '效果写入已关闭'
        elseif tostring(why):find('budget',1,true) then
            M.notice=M.lang=='en' and 'Limit: 11 rows. Remove perks.' or '超过11行上限 请减少词条'
        elseif tostring(why):find('unused independent',1,true) then
            M.notice=M.lang=='en' and 'No free carrier. Restore first.' or '载体不足 请先还原原版再切换'
        else
            M.notice=M.lang=='en' and 'Not loaded. View armor in Armory.' or '尚未加载 请先在军械库查看护甲'
        end
        log('ui: card '..c.label..' failed: '..tostring(why))
    end
    PANEL.sig=nil
end

local function ui_frame(conf_data,frames)
    ui_diag(frames,'enter')
    if not M.ship_ok then return end
    -- HARD GUARD: the engine's Gui library is not built during boot and its
    -- font/material slots still hold NULL there. The very first panel call
    -- (World.create_screen_gui) then faults at NATIVE level, which pcall cannot
    -- catch - the process survived by throwing ntdll 0xc0000026 every few
    -- seconds while the frame callback stayed dead. The ship world resolves
    -- around frame 600; nothing here may run before it exists.
    -- (Evidence: MultiPerk.log ended at 'building the panel'; no 'ladder 1', no
    -- 'frame error'; helldivers2.exe APPCRASH ntdll 0xc0000026.)
    if not M.ship_world then
        if not M.ui_noworld_log then
            M.ui_noworld_log=true
            log('ui: held - ship world not resolved yet (world=nil); panel work deferred')
        end
        ui_diag(frames,'stop:no-world')
        return
    end
    local sr=rawget(_G,'stingray')
    if type(sr)~='table' or type(sr.Gui)~='table' then
        if not M.ui_diag_stingray then M.ui_diag_stingray=true log('ui: stop - stingray table missing in this state') end
        return
    end
    if not (M.ui_font and M.ui_material) then
        -- 2.5.8: the scan used to run exactly once (M.ui_res_done) and, if the
        -- engine had not built its font/material libraries yet, the panel was
        -- abandoned for the whole session. The live dump proved the spec offsets
        -- are right and the hits are real - the slot simply holds NULL early on
        -- (font/atlas/material = 0x0 while manager is valid). Retry instead of
        -- giving up.
        local due=not M.ui_res_done or (frames-(M.ui_res_frame or 0))>=600
        if due then
            M.ui_res_frame=frames
            M.ui_res_tries=(M.ui_res_tries or 0)+1
            pcall(ui_resources)
            if M.ui_font and M.ui_material then
                M.ui_res_done=true
                log('ui: drawing resources acquired on try '..M.ui_res_tries)
            elseif M.ui_res_tries%10==1 or M.ui_res_tries<=3 then
                log('ui: drawing resources still missing (try '..M.ui_res_tries
                    ..') font='..tostring(M.ui_font)..' material='..tostring(M.ui_material))
            end
        end
        ui_diag(frames,'stop:no-resources')
        return
    end
    local okr,rw,rh=pcall(sr.Gui.resolution)
    if not okr or type(rw)~='number' or rw<640 or type(rh)~='number' or rh<480 then
        if not M.ui_diag_res then M.ui_diag_res=true log(string.format('ui: stop - resolution invalid ok=%s w=%s h=%s',tostring(okr),tostring(rw),tostring(rh))) end
        ui_diag(frames,'stop:bad-resolution')
        return
    end
    if PANEL.world~=M.ship_world then
        panel_clear()
        PANEL.world=M.ship_world
        if not PANEL.world then return end
        log('ui: verified main ship world acquired')
    end
    local oki,ix,iy,down=pcall(sample_input,sr,rw,rh)
    if not oki and not M.ui_diag_input then M.ui_diag_input=true log('ui: input sample error: '..tostring(ix)) end
    local input=ix and {x=ix,y=iy,down=down} or nil
    local dragging=panel_drag(sr,input,rw,rh)
    local dx,dy=panel_offset(sr,rw,rh)
    if input then input.x,input.y=input.x-dx,input.y-dy end
    -- click handling (press edge against the CURRENT regions)
    if not dragging and input and input.down and not PANEL.was_down then
        for _,r in ipairs(PANEL.regions) do
            if input.x>=r.x and input.x<r.x+r.w and input.y>=r.y and input.y<r.y+r.h then
                local a,idx=r.action,r.index
                if a=='open' then
                    PANEL.open=true
                    PANEL.sig=nil
                    log('ui: dock opened')
                elseif a=='close' then
                    PANEL.open=false
                    PANEL.sig=nil
                    log('ui: dock closed')
                elseif a=='card' then
                    card_action(conf_data,idx)
                elseif a=='del' then
                    local victim=conf_data.cards[idx]
                    local newlist={}
                    for i,c in ipairs(conf_data.cards) do
                        if i~=idx then newlist[#newlist+1]=c end
                    end
                    local ok,why=save_cards(newlist)
                    log(ok and ('ui: card '..idx..' deleted') or ('ui: delete failed: '..tostring(why)))
                    if ok and victim and ED.editing==victim.label then ED.editing=nil end
                    -- the auto re-apply path holds M.active_card in memory and
                    -- would resurrect a card the user just deleted
                    if ok and victim and M.active_card and M.active_card.label==victim.label then
                        restore_all()
                    end
                elseif a=='new' then
                    ED.mode='edit'
                    ED.editing=nil
                    ED.look,ED.stats,ED.rowsel,ED.perks,ED.page=nil,nil,{},{},1
                    ED.query,ED.ppage='',1
                elseif a=='editcard' then
                    -- load an existing card into the editor; save updates it
                    -- in place instead of appending a copy. Legacy tokens
                    -- (whole perk / enum.ri) resolve to concrete row hexes.
                    local c=conf_data.cards[idx]
                    if c then
                        ED.mode='edit'
                        ED.editing=c.label
                        ED.look,ED.stats=c.look,c.stats
                        ED.rowsel,ED.perks,ED.page={}, {},1
                        for _,e in ipairs(c.perks) do
                            if type(e)=='string' and #e==32 and not e:find('.',1,true) then
                                -- legacy hex row: find the perk that owns it
                                for en,p in pairs(PERKS) do
                                    for _,h in ipairs(p.m or {}) do
                                        if h==e then ED.perks[en]=true break end
                                    end
                                end
                            elseif type(e)=='string' then
                                local en=e:match('^(%d+)%.')
                                if en then ED.perks[tonumber(en)]=true end
                            else
                                ED.perks[e]=true
                            end
                        end
                                                ED.query,ED.ppage='',1
                        log('ui: editing '..c.label)
                    end
                elseif a=='pick' then
                    ED.mode='pick'
                    ED.query,ED.ppage='',1
                elseif a=='pickone' then
                    if idx then
                        ED.look=idx
                        ED.mode='edit'
                        if not S.kits[idx] then
                            log(string.format('ui: armor %x not loaded yet - view it in the armory once',idx))
                        end
                    end
                elseif a=='kv' then
                    -- on-screen keyboard letter (the game eats hardware keys)
                    if #(ED.query or '')<12 then
                        ED.query=(ED.query or '')..tostring(idx)
                        ED.ppage=1
                    end
                elseif a=='kbs' then
                    local q=ED.query or ''
                    if #q>0 then ED.query=q:sub(1,#q-1) ED.ppage=1 end
                elseif a=='kclr' then
                    ED.query=''
                    ED.ppage=1
                elseif a=='ppage' then
                    local owned=owned_list(M.conf_text)
                    local q=(ED.query or ''):lower()
                    local n=0
                    for _,id in ipairs(owned) do
                        if q=='' or ((PICKKEYS[string.format('%x',id)] or ''):find(q,1,true)) then
                            n=n+1
                        end
                    end
                    local pages=math.max(1,math.ceil(n/5))
                    ED.ppage=math.max(1,math.min(pages,ED.ppage+(idx or 1)))
                elseif a=='back' then
                    ED.mode=(ED.mode=='pick') and 'edit' or 'cards'
                    if ED.mode=='cards' then ED.editing=nil end
                elseif a=='look' then
                    local owned=owned_list(M.conf_text)
                    if #owned>0 then
                        local i=1
                        for j,id in ipairs(owned) do if id==ED.look then i=j break end end
                        i=math.max(1,math.min(#owned,i+(idx or 1)))
                        ED.look=owned[i]
                    end
                elseif a=='stats' then
                    -- cycle 未选择 -> 轻 -> 中 -> 重 -> 未选择; the editor keeps
                    -- a representative armor id of the class so apply stays
                    -- a plain donor copy
                    local owned=owned_list(M.conf_text)
                    local cur=stats_class(ED.stats)
                    local i=0
                    if cur then
                        for j=0,2 do if j==cur then i=j+1 break end end
                    end
                    i=i+(idx or 1)
                    if i<1 or i>3 then ED.stats=nil
                    else ED.stats=stats_rep(i-1,owned) end
                elseif a=='perk' then
                    if ED.perks[idx] then
                        ED.perks[idx]=nil
                    else
                        -- live row budget (never truncate - oversize merges are
                        -- refused, a truncated record fastfails the game)
                        local budget=conf_data.rows or 11
                        local selected={}
                        for e in pairs(ED.perks) do selected[#selected+1]=e end
                        selected[#selected+1]=idx
                        local data,why=compose(selected,budget)
                        if not data then
                            log('ui: '..tostring(why))
                        else ED.perks[idx]=true end
                    end
                elseif a=='page' then
                    -- must match the grid: filtered perks, 3 per page
                    local cenum=(S.carrier and S.carrier.enum) or conf_data.carrier
                    local n=#selectable_perks(cenum)
                    local pages=math.max(1,math.ceil(n/3))
                    ED.page=math.max(1,math.min(pages,ED.page+(idx or 1)))
                elseif a=='save' then
                    -- whole-perk selection, saved as plain perk enums
                    local plist={}
                    for e in pairs(ED.perks) do plist[#plist+1]=e end
                    table.sort(plist)
                    local newlist,label
                    if ED.editing then
                        -- editing an existing card: replace it in place
                        label=ED.editing
                        for _,c in ipairs(conf_data.cards) do
                            if c.label==label then
                                newlist=newlist or {}
                                newlist[#newlist+1]={label=label,look=ED.look,stats=ED.stats,perks=plist}
                            else
                                newlist=newlist or {}
                                newlist[#newlist+1]=c
                            end
                        end
                        newlist=newlist or {}
                    else
                        newlist={}
                        for _,c in ipairs(conf_data.cards) do newlist[#newlist+1]=c end
                        label='CARD '..(#newlist+1)
                        newlist[#newlist+1]={label=label,look=ED.look,stats=ED.stats,perks=plist}
                    end
                    local ok,why=save_cards(newlist)
                    if ok then
                        ED.mode='cards'
                        ED.editing=nil
                        local card=nil
                        for _,c in ipairs(newlist) do if c.label==label then card=c end end
                        if card then
                            local aok,awhy=apply_card(card,conf_data)
                            if not aok then
                                M.auto_queue[#M.auto_queue+1]=label
                                M.auto_retry_after=frames+180
                            end
                            log('ui: card '..label..' saved ('..#plist..' perks) apply='..tostring(aok)..(awhy and (' '..tostring(awhy)) or ''))
                        end
                    else
                        log('ui: save failed: '..tostring(why))
                    end
                elseif a=='restore' then
                    restore_all()
                end
                PANEL.sig=nil -- any interaction refreshes the panel
                break
            end
        end
    end
    if input then PANEL.was_down=input.down else PANEL.was_down=false end
    -- hover (only while no drag); row index only
    local hover=0
    if input and not input.down then
        for i,r in ipairs(PANEL.regions) do
            if r.action=='card' and input.x>=r.x and input.x<r.x+r.w and input.y>=r.y and input.y<r.y+r.h then
                hover=i break
            end
        end
    end
    PANEL.hover=hover
    -- staged bring-up first, then retained mode. Real engine steps pause
    -- 1s between them; no-op steps advance instantly.
    -- Last line of defence: nothing may build a screen GUI without a world.
    if not PANEL.world then
        ui_diag(frames,'stop:no-panel-world')
        return
    end
    if not PANEL.ladder_done then
        if frames>=PANEL.lnext then
            local step=PANEL.ladder
            local ok,note,err2
            ok,err2=ladder_step(step,conf_data,rw,rh)
            note=err2
            local LDELAY=1
            if ok then
                log('ui: ladder '..step..' ('..LNAMES[step]..') OK '..tostring(note or ''))
                if step==8 then
                    PANEL.ladder_done=true
                    if not M.said_panel then M.said_panel=true log('ui: dock ready (closed - click the strip)') end
                end
                PANEL.ladder=step+1
                PANEL.lnext=frames+LDELAY
            else
                PANEL.lfail=PANEL.lfail+1
                log('ui: ladder '..step..' ('..LNAMES[step]..') failed '..PANEL.lfail..'/3: '..tostring(err2))
                if PANEL.lfail>=3 then
                    PANEL.armed=false
                    M.ui_aborted=true
                    log('ui: ladder aborted - panel stays off until the config changes')
                else
                    PANEL.lnext=frames+60
                end
            end
        end
        ui_diag(frames,'ladder')
        return
    end
    -- signature: real state changes only (hover excluded - mouse sweeps must
    -- not trigger destroy/create rebuild storms)
    local active=M.active_card and M.active_card.label or '-'
    local nsel=0
    for _ in pairs(ED.perks) do nsel=nsel+1 end
    local sig=string.format('%dx%d|%s|%s|%s|%s|%s|%s|%d|%d|%s|%d|%s|%d|%d|%s',
        rw,rh,tostring(PANEL.world),active,
        PANEL.open and 'O' or 'C',tostring(ED.mode),tostring(ED.look or 0),
        tostring(ED.stats or 0),tonumber(ED.page) or 1,tonumber(nsel) or 0,
        table.concat((function()
            local t={} for _,c in ipairs(conf_data.cards) do t[#t+1]=c.label..#c.perks end return t
        end)(),';'),(S.carrier~=nil and kits_ready(conf_data)) and 1 or 0,
        tostring(ED.query or ''),(ED.ppage or 1),(S.kits_n or 0),(S.rows_rev or 0))
    if PANEL.sig==sig then
        if frames%3600==0 then log(string.format('ui: alive frames=%d steady',frames)) end
        ui_diag(frames,'steady')
        return
    end
    if frames<PANEL.retry then return end
    if frames<(PANEL.last_build or 0)+15 then return end
    PANEL.last_build=frames
    M.rebuilds=(M.rebuilds or 0)+1
    if M.rebuilds%50==1 then log('ui: rebuild count='..M.rebuilds) end
    panel_clear()
    local ok1,e1=ladder_step(1,conf_data,rw,rh)
    if not ok1 then
        PANEL.retry=frames+300
        log('ui: rebuild create failed: '..tostring(e1))
        return
    end
    local ok2=ladder_step(2,conf_data,rw,rh)
    local ok6=ok2 and ladder_step(6,conf_data,rw,rh)
    if ok2 and ok6 and PANEL.gui then
        PANEL.sig=sig
        PANEL.ladder_done=true
        PANEL.ladder=9
    else panel_clear() PANEL.retry=frames+60 end
    ui_diag(frames,'rebuilt')
end

local function rewrite_config_ui_auto()
    pcall(function()
        local f=io.open(CFG,'r')
        if not f then return end
        local t=f:read('*a') f:close()
        local function toauto(pre,val)
            if val=='once' or val=='yes' or val=='now' or val=='true' then return pre..'auto' end
            return nil
        end
        local n=0
        t,n=t:gsub('(\n%s*ui%s*=%s*)(%a+)',toauto)
        local first=t:match('^%s*ui%s*=%s*(%a+)') or ''
        local hit=first=='once' or first=='yes' or first=='now' or first=='true'
        if hit then
            t=t:gsub('^(%s*ui%s*=%s*)(%a+)',toauto)
            n=n+1
        end
        if n>0 then
            local w=io.open(CFG,'w')
            if w then w:write(t) w:close() end
        end
    end)
end

local previous=rawget(_G,'update')
local frames=0
local last_log=0
local wrapper
wrapper=function(...)
    local ok,err=pcall(function()
        frames=frames+1
        if rawget(_G,'update')~=wrapper and frames<300 then
            if frames==120 then log('WARNING: _G.update no longer points at this mod (loader replaced it)') end
        end
        if frames<2 then return end
        if not M.conf_text or frames%120==0 then
            local raw=io.open(CFG,'r')
            if raw then
                local text=raw:read('*a');raw:close()
                if text~=M.conf_text then
                    M.conf_text=text
                    M.dirty=true
                    M.broken,M.reapply_fails=nil,0
                    M.ui_aborted=nil
                    if M.booted then log('config changed - re-applying') end
                end
            end
        end
        local conf_data,why=conf(M.conf_text)
        if not conf_data then
            if frames%600==0 then log('config: '..tostring(why)) end
            return
        end
        -- A gate_fallback/gate_hold change must rebuild the gate: the old
        -- object still holds the previous session_required decision.
        if M.conf_fallback~=nil and (M.conf_fallback~=conf_data.gate_fallback
            or M.conf_hold~=conf_data.gate_hold
            or M.conf_ship~=conf_data.gate_ship) then
            VISIBILITY=nil
            M.gate_latched,M.gate_world,M.gate_streak=nil,nil,0
            log('gate options changed - rebuilding the ship gate')
        end
        -- ui reconciliation: off/no/false/hide -> dormant; once/yes/now/true
        -- -> arm now (line falls back to auto); auto/absent -> arm 120s after
        -- launch, safely past the loading phase
        local ship_ok,ship_reason,ship_world=ship_visible()
        M.ship_ok,M.ship_reason,M.ship_world=ship_ok,ship_reason,ship_world
        gate_heartbeat(frames,ship_ok,ship_reason,ship_world)
        -- Run the bounded one-shot scene survey as soon as a real session
        -- exists. Waiting for a visible gate was wrong: on this build the
        -- marker predicate never succeeds, so the survey never ran and we had
        -- no evidence about which world actually carries the ship resources
        -- (MultiPerk.log 2026-10-01T11:24:20Z: markers=0 for 18k+ frames).
        visibility_diagnostics(frames,M.gate_info)
        if not ship_ok and PANEL.gui and not PANEL.suppressed then
            PANEL.suppressed=true
            PANEL.open=false
            panel_clear()
            PANEL.sig=nil
            log('ui: hidden ('..tostring(ship_reason)..')')
        elseif ship_ok and PANEL.suppressed then
            PANEL.suppressed=false
            PANEL.sig=nil
        end
        -- The armory draws its own full-screen layer, and the engine keeps a
        -- retained screen GUI's primitives until that GUI is recreated - so a
        -- panel built before the armory opened stays covered by it. Recreate
        -- the panel whenever the native screen changes while the panel is
        -- authorized, which gives the armory its own freshly built copy.
        do
            local screen=(M.gate_info and M.gate_info.ui and M.gate_info.ui.screen) or 0
            if screen~=M.ui_screen then
                local was=M.ui_screen
                M.ui_screen=screen
                if PANEL.armed and M.ship_ok and was~=nil then
                    PANEL.sig=nil
                    log('ui: native screen '..tostring(was)..' -> '..tostring(screen)
                        ..' worlds='..ui_world_count()..' (panel redraw requested)')
                end
            end
        end
        local v=conf_data.ui or 'auto' 
        M.ui_text=conf_data.text
        M.statrows=conf_data.statrows
        -- A layer change must rebuild: a retained GUI keeps its old primitives,
        -- so the panel would otherwise be drawn at the old layer as well.
        if M.ui_layer~=conf_data.layer then
            M.ui_layer=conf_data.layer
            PANEL.sig=nil
            log('ui: draw layer -> '..tostring(M.ui_layer)..' (panel redraw requested)')
        end
        M.conf_fallback=conf_data.gate_fallback
        M.conf_hold=conf_data.gate_hold
        M.conf_ship=conf_data.gate_ship
        update_language(conf_data.lang,frames)
        -- Prewarm only read-only resources; GUI creation still waits for ESC.
        if M.gate_info and M.gate_info.in_session==true and not M.ui_res_done
            and (not M.ui_res_frame or frames-M.ui_res_frame>=120) then
            M.ui_res_frame=frames
            pcall(ui_resources)
            M.ui_res_done=(M.ui_font~=nil and M.ui_material~=nil)
        end
        if v=='off' or v=='no' or v=='false' or v=='hide' then
            M.ui_blocked=true
            if PANEL.armed then PANEL.armed=false panel_clear() log('ui: panel hidden') end
        elseif v=='once' or v=='yes' or v=='now' or v=='true' then
            M.ui_blocked=false
            if not PANEL.armed and not M.ui_aborted and M.ship_ok then
                PANEL.armed=true
                PANEL.retry=frames+60
                log('ui: panel armed (ui='..v..')')
            end
            rewrite_config_ui_auto()
        else
            M.ui_blocked=false
            if not PANEL.armed and not M.ui_aborted and M.ship_ok then
                PANEL.armed=true
                PANEL.retry=frames+1
                log('ui: panel armed (ESC GAME tab)')
            end
        end
        -- localization probe runs alongside the main sweep when probe=yes;
        -- delayed past the fragile load window so it never adds to the
        -- early-game scan pressure
        if M.ship_ok and conf_data.probe and not PROBE.done and frames%60==0
            and os.clock()-M.boot_clock>120 then
            probe_loc(os.clock()+0.004)
        end
        -- Only spend scan time while an idle ship needs a target/candidate.
        -- Language detection and unused kit discovery do not keep a full sweep alive.
        local desired=0
        for _,card in ipairs(conf_data.cards) do if #card.perks>0 then desired=1 break end end
        local available=0
        for en in pairs(S.carriers) do if en~=0 then available=available+1 end end
        local needs_scan=not S.initial_scan_done or not scan_targets_ready(conf_data) or (desired>0 and available<desired)
            or M.scan_requested or (ED.look and not S.kits[ED.look])
        local data_work=needs_scan or #M.auto_queue>0 or M.dirty or frames%120==0
        local data_ok=data_work and data_ship_ready()
        if data_ok and needs_scan then
            M.scan_started=M.scan_started or os.clock()
            if S.pass_done and (not M.scan_retry_after or frames>=M.scan_retry_after) then
                S.pass_done=false
                S.scanned,S.cursor,S.cur=0,4294967296,nil
                S.pri={active=true,cursor=1099511627776,top=8796093022208}
                M.scan_retry_after=frames+600
            end
            if S.scanned<S.limit and not S.pass_done then
                scan(conf_data,os.clock()+0.010)
                if not S.pri.active then S.initial_scan_done=true end
                if S.pass_done or S.scanned>=S.limit then M.scan_retry_after=frames+600 end
            end
            if not S.carrier and next(S.carriers) then
                local _,record=next(S.carriers)
                S.carrier=record
            end
            if os.clock()-last_log>5 then
                last_log=os.clock()
                log(string.format('scan: frames=%d read=%dMB candidates=%d requested=%d',
                    frames,math.floor(S.scanned/1048576),available,desired))
            end
        end
        local ready=S.carrier~=nil and kits_ready(conf_data)
        -- background apply of the pending card (remembered in active.txt or
        -- just saved): retries every 10s while the sweep catches up, instead
        -- of failing once and waiting for a manual click
        if S.carrier and #M.auto_queue>0
            and data_ok
            and (not M.auto_retry_after or frames>=M.auto_retry_after) then
            local lab=M.auto_queue[1]
            local def=card_by_label(conf_data,lab)
            if def then
                if (M.actives and M.actives[def.look] and M.actives[def.look].card.label==lab)
                    or (not M.actives and M.active_card and M.active_card.label==lab) then
                    table.remove(M.auto_queue,1)
                else
                local ok,why=apply_card(def,conf_data)
                if ok then
                    table.remove(M.auto_queue,1)
                    M.auto_retry_after=frames+60
                    M.auto_tries=nil
                    M.auto_done=true
                    log('auto: card '..lab..' applied')
                else
                    M.auto_retry_after=frames+600
                    M.auto_tries=(M.auto_tries or 0)+1
                    if M.auto_tries==1 then
                        log('auto: card '..lab..' pending - '..tostring(why))
                    elseif M.auto_tries>=60 then
                        log('auto: gave up on card '..lab..' after '..M.auto_tries..' tries')
                        table.remove(M.auto_queue,1)
                        M.auto_tries=nil
                    end
                end
                end
            else
                log('auto: remembered card "'..tostring(lab)..'" is not in the config')
                table.remove(M.auto_queue,1)
            end
        end
        if ready and data_ok then
            if not M.broken and (M.dirty or (frames%120==0 and not steady_all())) then
                local failed=nil
                local cards={}
                for _,active in pairs(M.actives or {}) do
                    cards[#cards+1]=card_by_label(conf_data,active.card.label) or active.card
                end
                for _,card in ipairs(cards) do
                    local ok,why2=apply_card(card,conf_data)
                    if not ok then failed=why2 break end
                end
                if failed then
                    M.reapply_fails=(M.reapply_fails or 0)+1
                    log('re-apply: '..tostring(failed)..' ('..M.reapply_fails..'/10)')
                    if M.reapply_fails>=10 then M.broken=true end
                else M.reapply_fails=0 end
                M.dirty=nil
            end
        end
        development_step(conf_data,frames)
        if PANEL.armed and M.ship_ok then ui_frame(conf_data,frames) end
    end)
    if not ok then
        M.ferr=(M.ferr or 0)+1
        if M.ferr<=5 or M.ferr%600==0 then log('frame error '..M.ferr..': '..tostring(err)) end
    end
    if previous then return previous(...) end
end
M.auto_queue={}
do
    local s=load_active()
    if s then
        for lab in s:gmatch('[^,]+') do M.auto_queue[#M.auto_queue+1]=lab end
    end
end
M.boot_clock=os.clock()
rawset(_G,'update',wrapper)
log('ready')
