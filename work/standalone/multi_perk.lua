end

-- write the merged effect rows of `list` into the carrier record. Buffer +
-- header writes + read-backs are the sequence verified in game since 0.4.x.
-- one RW window for the whole record head: wr() restores page protection
-- after each write, and pages carrying guard/write-watch flags make the NEXT
-- write fail (+16 ok, +32 'write' error). Keep the window open across all
-- head writes instead.
local function protect_rw(at,n)
    local mbi=ffi.new('uint8_t[48]')
    if k.VirtualQuery(ffi.cast('const void*',at),mbi,48)~=48 then return nil end
    local raw=ffi.string(mbi,48)
    local old=u32(raw,36) or 0
    if old%256==4 or old%256==8 then return old end
    local o=ffi.new('uint32_t[1]')
    if k.VirtualProtect(ffi.cast('void*',at),n,4,o)==0 then return nil end
    return old
end
local function protect_set(at,n,prot)
    if not prot or prot==0 then return end
    local o=ffi.new('uint32_t[1]')
    k.VirtualProtect(ffi.cast('void*',at),n,prot,o)
end

-- merged-row buffers live in VirtualAllocEx pages, not the LuaJIT heap
-- (proven layout for 20+ row arrays; our ffi heap buffers destabilized
-- the game's reader at >=12 rows)
local function wr_raw(at,bytes)
    local got=ffi.new('size_t[1]')
    if k.WriteProcessMemory(k.GetCurrentProcess(),ffi.cast('void*',at),
        ffi.cast('const void*',bytes),#bytes,got)==0 then return false end
    return tonumber(got[0])==#bytes
end

local function valloc(n)
    local p=k.VirtualAllocEx(k.GetCurrentProcess(),nil,n,0x3000,0x04)
    if p==nil then return nil end
    return tonumber(ffi.cast('uintptr_t',p))
end

local function merge_carrier(c,list,budget)
    local c=c
    local head=rd(c.body,56)
    if not head then S.carriers[c.enum]=nil return nil,'carrier unreadable - rescanning' end
    if u32(head,0)~=c.enum then S.carriers[c.enum]=nil return nil,'carrier enum changed - rescanning' end
    -- pristine OR already ours; a foreign change means the record moved
    local pristine=u32(head,4)==PERKS[c.enum].n and u64(head,16)==c.body+56
    -- ownership proof by BUFFER POINTER: survives carrier re-picks that lose
    -- the name_now table state (the old name check deadlocked applies)
    local bk=M.bufs and M.bufs[c.enum]
    local ours_ptr=bk and bk.at and u64(head,16)==bk.at
    local ours=(ours_ptr) or (u32(head,4)==(c.name_now or PERKS[c.enum].n)
        and u64(head,16)==(c.buf_at or c.body+56))
    if not (pristine or ours) then
        -- full forensics: actual record head vs every expectation
        log(string.format('carrier identity: enum=%d name=%s(want pristine %s / ours %s) ptr=%s(want %s / %s)',
            c.enum,tostring(u32(head,4)),tostring(PERKS[c.enum].n),tostring(c.name_now),
            tostring(u64(head,17)),tostring(c.body+56),tostring(c.buf_at)))
        log('carrier head hex: '..(head:sub(1,32):gsub('.',function(ch) return string.format('%02x',ch:byte()) end)))
        S.carriers[c.enum]=nil
        drop_carrier('carrier identity changed')
        return nil,'carrier identity changed - rescanning'
    end
    M.orig=M.orig or {}
    M.orig_body=M.orig_body or {}
    if pristine and (not M.orig[c.enum] or M.orig_body[c.enum]~=c.body) then
        -- Game reloads may move a record; an old inline pointer belongs to
        -- the previous allocation and cannot be restored into this one.
        M.orig[c.enum],M.orig_body[c.enum]=head,c.body
    end
    -- Only the empty passive is invalid. The carrier's own effects come
    -- from the pristine RT/catalog snapshot, never from its merged buffer.
    local clean={}
    for _,e in ipairs(list) do
        local en=e
        if type(e)=='string' and e:find('.',1,true) then
            en=tonumber(e:match('^(%d+)%.') or '')
        elseif type(e)=='string' then
            en=nil -- full row-hex token: no perk context needed
        end
        if (en==nil) or en~=0 then clean[#clean+1]=e end
    end
    if #clean~=#list then
        log(string.format('merge: dropped %d empty perk enum(s) (carrier %d)',#list-#clean,c.enum))
    end
    list=clean
    local data,why=compose(list,budget)
    if not data then return nil,'compose: '..tostring(why) end
    -- Private development probe: only localization is suppressed, preserving
    -- the actual effect bytes and both array lengths. Disabled in normal play.
    if M.test_tooltip_rows then
        local rows,shown={},0
        for i=1,data.nmod do
            local row=data.mods:sub((i-1)*16+1,i*16)
            if u32(row,12)~=0 then
                shown=shown+1
                if shown>M.test_tooltip_rows then row=row:sub(1,12)..p32(0) end
            end
            rows[i]=row
        end
        data.mods=table.concat(rows)
    end
    -- the game keeps reading this buffer, so it must never be freed; reusing
    -- the one buffer per perk set keeps the retained pool from growing on
    -- every re-apply (content verified before reuse)
    local key=table.concat(list,',')
    local want_all=data.mods..data.stats
    M.bufs=M.bufs or {}
    local bk=M.bufs[c.enum] or {}
    M.bufs[c.enum]=bk
    local at
    if bk.key==key and bk.at and rd(bk.at,#want_all)==want_all then
        at=bk.at
    else
        at=valloc(#want_all)
        if not at then return nil,'VirtualAllocEx failed' end
        if not wr_raw(at,want_all) then return nil,'buffer content write failed' end
        bk.key,bk.at=key,at
    end
    if not at or at<65536 then return nil,'buffer pointer rejected' end
    -- Keep the carrier's native display identity. The custom menu displays
    -- the selected effects; engine localization metadata remains paired.
    data.name=u32((M.orig[c.enum] or head),4)
    local want16=p64(at)..p64(data.nmod)
    local want32=data.nstat>0 and (p64(at+#data.mods)..p64(data.nstat)) or string.rep('\0',16)
    local orig=M.orig and M.orig[c.enum]
    local function undo()
        if orig then
            wr(c.body+4,orig:sub(5,8));wr(c.body+16,orig:sub(17,32));wr(c.body+32,orig:sub(33,48))
        end
    end
    -- NOTE: the record's declared length must NOT be rewritten. Changing it made
    -- the game treat the whole passive record as invalid (verified in game, 0.4.3).
    local pold=protect_rw(c.body,64)
    if pold==nil then return nil,'head page protect failed' end
    local ok1,why1=wr(c.body+16,want16)
    if not ok1 or rd(c.body+16,16)~=want16 then
        log(string.format('mod header write failed at 0x%x ok=%s why=%s',c.body,tostring(ok1),tostring(why1)))
        protect_set(c.body,64,pold)
        S.carriers[c.enum]=nil
        drop_carrier('modifier header unwritable')
        return nil,'modifier header '..tostring(why1)
    end
    local ok2,why2=wr(c.body+32,want32)
    if not ok2 or rd(c.body+32,16)~=want32 then
        -- this record is unhealthy (e.g. header straddles a protected page):
        -- forensics, then fail over to a different carrier record
        local now=rd(c.body+32,16) or ''
        log(string.format('stat header write failed at 0x%x ok=%s why=%s want=%s got=%s',
            c.body+32,tostring(ok2),tostring(why2),
            (want32:gsub('.',function(ch) return string.format('%02x',ch:byte()) end)),
            (now:gsub('.',function(ch) return string.format('%02x',ch:byte()) end))))
        undo()
        protect_set(c.body,64,pold)
        S.carriers[c.enum]=nil
        drop_carrier('stat header unwritable')
        M.pin_relaxed=true
        return nil,'stat header '..tostring(why2)
    end
    if data.name and u32(head,4)~=data.name then
        local ok3=wr(c.body+4,p32(data.name))
        if not ok3 or u32(rd(c.body,16) or '',4)~=data.name then undo() protect_set(c.body,64,pold) return nil,'name id' end
    end
    protect_set(c.body,64,pold)
    -- evidence log: row ids come from compose (scope-safe)
    log('merge rows ('..data.nmod..'): '..table.concat(data.rows or {},','))
    return {name=data.name,at=at,nmod=data.nmod,nstat=data.nstat}
end

