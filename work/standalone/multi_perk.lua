            M.ui_pattern_hits=M.ui_pattern_hits or {}
            local hit,start=M.ui_pattern_hits[spec.s],b
            while start<b+0x10000000 and not hit do
                local buf=rd(start,262144)
                if not buf then break end
                local at=1
                while true do
                    local found=buf:find(anchor,at,true)
                    if not found then break end
                    local cand=start+found-1-(from-1)
                    if cand>=b then
                        local win=rd(cand,#pat)
                        if win and #win==#pat then
                            local good=true
                            for j=1,#pat do
                                if bit.band(win:byte(j),mask:byte(j))~=bit.band(pat:byte(j),mask:byte(j)) then
                                    good=false break
                                end
                            end
                            if good then hit=cand end
                        end
                    end
                    if hit then break end
                    at=found+1
                end
                start=start+262144-#pat-4
            end
            if hit then
                M.ui_pattern_hits[spec.s]=hit
                local disp=u32(rd(hit+spec.o,4) or '',0)
                if disp and disp>=2147483648 then disp=disp-4294967296 end
                local handle=rd(hit+spec.e+(disp or 0),8)
                local value=handle and u64(handle,0) or nil
                -- the material slot holds a POINTER, the real font-material
                -- id64 lives 24 bytes into it; font/atlas slots hold ids
                -- directly. Chasing/validating matters: a wrong id makes
                -- G.material return a garbage ink and set_scalar faults at
                -- native level (pcall cannot catch that).
                if spec.s=='material' and value and value>65536 and value<281474976710656 then
                    local real=rd(value+24,8)
                    if real then value=u64(real,0) end
                end
                -- id64 sanity gate: real ids are huge (>= 2^48); anything
                -- smaller smells like a pointer or garbage -> refuse it
                if spec.s~='manager' and value and value<281474976710656 then
                    log(string.format('ui: %s value 0x%x does not look like an id64 - rejected',spec.s,value))
                    value=nil
                end
                M['ui_'..spec.s]=value
                log(string.format('ui: %s=%s (at 0x%x)',spec.s,
                    value and string.format('0x%x',value) or 'nil',hit))
            else
                log('ui: '..spec.s..' pattern not found')
            end
        end
    end
end

