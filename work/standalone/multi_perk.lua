local function sample_input(sr,rw,rh)
    local win=u.GetForegroundWindow()
    if win==nil then return nil end
    if tonumber(u.GetWindowThreadProcessId(ffi.cast('void*',win),ffi.cast('void*',ui_pid)))==0 then return nil end
    if ui_pid[0]~=tonumber(k.GetCurrentProcessId()) then return nil end
    if u.GetCursorPos(ffi.cast('void*',ui_point))==0 then return nil end
    if u.ScreenToClient(ffi.cast('void*',win),ffi.cast('void*',ui_point))==0 then return nil end
    if u.GetClientRect(ffi.cast('void*',win),ffi.cast('void*',ui_rect))==0 then return nil end
    local w,h=ui_rect[2]-ui_rect[0],ui_rect[3]-ui_rect[1]
    if not(w>0 and h>0) then return nil end
    local cx,cy=ui_point[0],ui_point[1]
    if cx<0 or cy<0 or cx>=w or cy>=h then return nil end
    local down=false
    -- hardware-level button state: the engine's Mouse.button reports
    -- unreliably in menu states, which made clicks feel dead in the Armory
    local ks=tonumber(u.GetAsyncKeyState(0x01))
    if ks~=nil and ks<0 then down=true end
    -- top-left client pixels -> bottom-left Gui units
    return cx*rw/w,(h-cy)*rh/h,down
end

