local function conf(cached)
    local text=cached
    if not text then
        local f=io.open(CFG,'r')
        if not f then
            pcall(function()
                -- CreateDirectoryW via FFI: spawning a shell from the update
                -- thread hung one reporter's game at frame 120
                local dir=HOME..'MultiPerk'
                local d=io.open(dir,'r')
                if not d then
                    local wdir=ffi.new('uint16_t[?]',#dir+1)
                    for i=1,#dir do wdir[i-1]=string.byte(dir,i) end
                    wdir[#dir]=0
                    pcall(function() k.CreateDirectoryW(wdir,nil) end)
                end
                local w=io.open(CFG,'w')
                if w then
                    w:write('# Custom Armor Kit config\n')
                    w:write('# lang=zh forces Chinese, lang=en English; default auto-detects\n')
                    w:write('# rows= merge row budget (stable maximum 11)\n\n')
                    w:write('ui=auto\nwrite=yes\n')
                    w:write('# create your first card from the in-game panel\n')
                    w:close()
                end
            end)
            return nil,'no config'
        end
        text=f:read('*a');f:close()
    end
    -- only real assignments count: skip comments, require the whole line
    local target,write,perks,carrier,stats,card,ui,cards,textopt,keyname=nil,nil,{},nil,nil,nil,nil,{},false,nil
    local probeopt=false
    local rowbudget=11
    local uilayer=980     -- Gui draw layer for every panel primitive
    local langopt='auto'  -- auto-detect; zh/en force
    local uiscope='ship'  -- 2.4.0 default: ship-only. ui_scope=all opts into P2P-style
    local armgate=0       -- session/ship state gates visibility; no artificial delay
    local statrows=true -- native dynamic reload/ammo rows are required gameplay data
    -- 2.5.7: the ship gate trusts GameSession.in_session() when it answers
    -- true. gate_fallback=yes additionally allows "native UI idle plus the
    -- three live ship markers, held for gate_hold frames" to authorize the
    -- panel on builds where that session helper never answers true. A firm
    -- false from the helper is only overridden in fallback mode.
    local gatefallback=true
    local gatehold=10
    -- 2.5.8: which world may be the ship. 'any' searches the bounded worlds
    -- list for the world that actually carries all three ship markers; 'main'
    -- keeps the old Application.main_world() assumption, which the live
    -- 2026-10-01 11:13 run disproved on this build (real session, in_session
    -- true, main world markers=0 for 18k+ frames -> panel hidden all run).
    local gateship='count'
    for line in text:gmatch('[^\r\n]+') do
        local value
        value=line:match('^%s*target%s*=%s*(%x+)%s*$')
        if value then target=tonumber(value,16) end
        value=line:match('^%s*card%s*=%s*(%x+)%s*$')
        if value then card=tonumber(value,16) end
        value=line:match('^%s*stats%s*=%s*(%x+)%s*$')
        if value then stats=tonumber(value,16) end
        value=line:match('^%s*carrier%s*=%s*(%d+)%s*$')
        if value then carrier=tonumber(value) end
        value=line:match('^%s*ui%s*=%s*(%a+)%s*$')
        if value then ui=value end
        value=line:match('^%s*text%s*=%s*(%a+)%s*$')
        if value then textopt=(value=='yes' or value=='true') end
        value=line:match('^%s*write%s*=%s*(%a+)%s*$')
        if value then write=value end
        value=line:match('^%s*probe%s*=%s*(%a+)%s*$')
        if value then probeopt=(value=='yes' or value=='true') end
        value=line:match('^%s*rows%s*=%s*(%d+)%s*$')
        if value then rowbudget=math.max(1,math.min(11,tonumber(value) or 11)) end
        -- Gui draw layer for every panel primitive. The panel has always used
        -- 980; the native menus draw into the same Gui system, so a screen that
        -- covers the panel is a screen whose own primitives sit above 980.
        value=line:match('^%s*layer%s*=%s*(%d+)%s*$')
        if value then uilayer=math.max(0,math.min(1000000,tonumber(value) or 980)) end
        value=line:match('^%s*lang%s*=%s*(%a+)%s*$')
        if value then langopt=value end
        value=line:match('^%s*ui_scope%s*=%s*(%a+)%s*$')
        if value then uiscope=(value=='ship') and 'ship' or 'all' end
        value=line:match('^%s*arm_s%s*=%s*(%d+)%s*$')
        if value then armgate=math.max(0,math.min(600,tonumber(value) or 0)) end
        value=line:match('^%s*statrows%s*=%s*(%a+)%s*$')
        if value then statrows=true end -- legacy flag must not drop actual effects
        value=line:match('^%s*gate_fallback%s*=%s*(%a+)%s*$')
        if value then gatefallback=(value=='yes' or value=='true') end
        value=line:match('^%s*gate_strict%s*=%s*(%a+)%s*$')
        if value then gatefallback=not(value=='yes' or value=='true') end
        value=line:match('^%s*gate_hold%s*=%s*(%d+)%s*$')
        if value then gatehold=math.max(1,math.min(600,tonumber(value) or 10)) end
        value=line:match('^%s*gate_ship%s*=%s*(%a+)%s*$')
        if value then gateship=(value=='main') and 'main' or 'any' end
        value=line:match('^%s*perks%s*=%s*([%d%%,%s]*)%s*$')
        if value then
            perks={}
            for n in value:gmatch('%d+') do perks[#perks+1]=tonumber(n) end
        end
        -- card.N = label, look-armor-hex, stats-donor-hex, perk,perk,...
        local idx,label,look,donor,list=line:match('^%s*card%.-(%d+)%s*=%s*([^,]+),(%x+),(%x*),([%x%s,.]*)$')
        if idx then
            local plist={}
            for n in list:gmatch('[%x.]+') do
                if #n==32 and not n:find('.',1,true) then
                    plist[#plist+1]=n -- full row-hex token
                elseif n:find('.',1,true) then
                    plist[#plist+1]=n -- legacy row token enum.ri
                else
                    local e=tonumber(n)
                    -- enum 0 is the empty passive; merging it corrupts the
                    -- record the game reads on hover, so old configs are
                    -- sanitized here
                    if e~=0 then plist[#plist+1]=e end
                end
            end
            cards[#cards+1]={label=label:gsub('%s+$',''):gsub('^%s+',''),look=tonumber(look,16),
                stats=#donor>0 and tonumber(donor,16) or nil,perks=plist}
        end
    end
    if #cards==0 and (target or card) then
        -- legacy single-card config keeps working unchanged
        cards[1]={label='CUSTOM',look=card or target,stats=stats,perks=perks}
    end
    local want_items={}
    for _,c in ipairs(cards) do want_items[c.look]=true end
    return {target=target,perks=perks,carrier=carrier or 37,stats=stats,card=card,cards=cards,
        want_items=want_items,ui=ui,text=textopt,
        probe=probeopt,rows=rowbudget,lang=langopt,statrows=statrows,
        uiscope=uiscope,arm_s=armgate,gate_fallback=gatefallback,gate_hold=gatehold,gate_ship=gateship,
        layer=uilayer,
        write=(write=='yes' or write=='true')},nil
end

